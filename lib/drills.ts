function buildPassage(sentences: SentenceItem[]): PassageItem {
  const spanish = sentences.map((s) => s.spanish).join(" ");
  const english = sentences.map((s) => s.english).join(" ");
  const traps = sentences.flatMap((s) => s.traps);
  return {
    id: "passage-medellin",
    mode: "passage",
    title: "Medellín transit plan",
    spanish,
    english,
    domain: "journalistic",
    wordCount: wordCount(spanish),
    translationInstructions: {
      sourceMedium: "Newspaper feature, Medellín",
      targetMedium: "US English newspaper brief",
      purpose: "Tell a US reader what the city proposed, with the figures and the limits intact",
      audience: "General readers of a national US paper who do not know the city administration",
    },
    sentences,
    focus: [...new Set(traps.map((t) => t.pitfall))],
    errors_to_catch: traps.map((t) => t.label),
  };
}

export const PASSAGE: PassageItem = buildPassage(passageSentences);

export function bankCounts() {
  const counts: Record<string, number> = {};
  for (const item of MICROS) counts[item.bank] = (counts[item.bank] ?? 0) + 1;
  return counts;
}

export function validateContent(): void {
  const problems: string[] = [];
  for (const item of MICROS) {
    const focus = [...new Set(item.traps.map((t) => t.pitfall))];
    if (focus.join("|") !== item.focus.join("|")) problems.push(`${item.id} focus drifted`);
    if (item.errors_to_catch.join("|") !== item.traps.map((t) => t.label).join("|")) {
      problems.push(`${item.id} errors_to_catch drifted`);
    }
    for (const t of item.traps) {
      if ((t.category === "P" || t.category === "SP") && t.weightIfMissed > 4) {
        problems.push(`${t.id} mechanical weight ${t.weightIfMissed}`);
      }
    }
    const grade = gradeItem(item, item.english, { mode: "micro" });
    if (grade.points !== 0) {
      problems.push(`${item.id} key scored ${grade.points} (${grade.fired.map((f) => f.trapId + ":" + f.code).join(", ")})`);
    }
    for (const alt of item.acceptables ?? []) {
      const g = gradeItem(item, alt, { mode: "micro" });
      if (g.points !== 0) problems.push(`${item.id} acceptable scored ${g.points}: ${alt}`);
    }
  }
  const counts = bankCounts();
  for (const bank of ["O", "P", "POS"] as Bank[]) {
    if ((counts[bank] ?? 0) < 10) problems.push(`bank ${bank} has ${counts[bank] ?? 0}`);
  }
  if (PASSAGE.wordCount < 225 || PASSAGE.wordCount > 275) {
    problems.push(`passage word count ${PASSAGE.wordCount}`);
  }
  const pieces = splitEnglishSentences(PASSAGE.english);
  if (pieces.length !== PASSAGE.sentences.length) {
    problems.push(`passage split ${pieces.length} != ${PASSAGE.sentences.length}`);
  }
  for (const s of PASSAGE.sentences) {
    const g = gradeItem(s, s.english, { mode: "sentence", builtins: false });
    if (g.points !== 0) problems.push(`${s.id} key scored ${g.points} (${g.fired.map((f) => f.trapId).join(",")})`);
  }
  const whole = gradePassage(PASSAGE, PASSAGE.english);
  if (whole.points !== 0) {
    problems.push(`passage key scored ${whole.points} (${whole.fired.map((f) => f.trapId).join(",")})`);
  }
  if (problems.length) {
    throw new Error(`Drill content invalid:\n${problems.join("\n")}`);
  }
}

validateContent();

export function getMicro(id: string): DrillItem | undefined {
  return MICROS.find((m) => m.id === id);
}

const BANK_FOR_CATEGORY: Partial<Record<ErrorCat, Bank>> = {
  O: "O",
  P: "P",
  T: "POS",
  SP: "titles",
  U: "U",
  SYN: "POS",
  G: "P",
  A: "O",
  IND: "P",
};

export function selectMicros(opts: {
  bank?: string;
  count: number;
  itemId?: string;
  heat: Record<string, number>;
  weakest?: ErrorCat;
  todayTrapIds?: string[];
  todayPitfalls?: string[];
  todayLemmas?: string[];
  todayCategories?: ErrorCat[];
}): DrillItem[] {
  if (opts.itemId) {
    const one = getMicro(opts.itemId);
    return one ? [one] : [];
  }
  let pool = MICROS.slice();
  const bank = opts.bank;
  if (bank === "O" || bank === "P" || bank === "POS" || bank === "titles" || bank === "U") {
    pool = pool.filter((m) => m.bank === bank);
  } else if (bank === "weak") {
    const cat = opts.weakest ?? "O";
    const preferred = BANK_FOR_CATEGORY[cat] ?? "O";
    const tagged = pool.filter((m) => m.traps.some((t) => t.category === cat) || m.bank === preferred);
    pool = tagged.length ? tagged : pool.filter((m) => m.bank === preferred);
  } else if (bank === "today") {
    const ids = new Set(opts.todayTrapIds ?? []);
    const pitfalls = new Set(opts.todayPitfalls ?? []);
    const lemmas = new Set((opts.todayLemmas ?? []).filter(Boolean));
    const cats = new Set(opts.todayCategories ?? []);
    const matched = pool.filter((m) =>
      m.traps.some(
        (t) =>
          ids.has(t.id) ||
          pitfalls.has(t.pitfall) ||
          (!!t.lemma && lemmas.has(t.lemma)) ||
          cats.has(t.category)
      )
    );
    pool = matched.length ? matched : pool.filter((m) => m.bank === (BANK_FOR_CATEGORY[opts.weakest ?? "O"] ?? "O"));
  }
  const ranked = pool
    .map((item) => ({
      item,
      heat: item.traps.reduce((sum, t) => sum + (opts.heat[t.id] ?? 0), 0),
    }))
    .sort((a, b) => b.heat - a.heat || a.item.id.localeCompare(b.item.id));
  return ranked.slice(0, opts.count).map((r) => r.item);
}
