function passFor(category: ErrorCat): "A" | "B" {
  return category === "P" || category === "SP" || category === "G" || category === "IND" ? "A" : "B";
}

function trap(spec: {
  id: string;
  category: ErrorCat;
  weight: Weight;
  detector: DetectorSpec;
  comment: string;
  ok?: string;
  no?: string;
  pitfall: string;
  label: string;
  lemma?: string;
}): Trap {
  return {
    id: spec.id,
    category: spec.category,
    weightIfMissed: spec.weight,
    detector: spec.detector,
    comment: spec.comment,
    okExample: spec.ok,
    noExample: spec.no,
    pitfall: spec.pitfall,
    label: spec.label,
    lemma: spec.lemma,
    pass: passFor(spec.category),
  };
}

function micro(spec: {
  id: string;
  bank: Bank;
  spanish: string;
  english: string;
  acceptables?: string[];
  domain: string;
  level?: string;
  traps: Trap[];
}): DrillItem {
  return {
    id: spec.id,
    mode: "micro",
    bank: spec.bank,
    spanish: spec.spanish,
    english: spec.english,
    acceptables: spec.acceptables,
    domain: spec.domain,
    level: spec.level,
    focus: [...new Set(spec.traps.map((t) => t.pitfall))],
    errors_to_catch: spec.traps.map((t) => t.label),
    traps: spec.traps,
  };
}

